#!/usr/bin/env python3
"""Regenerate chess-core/src/key_table.rs from a reference tree's key-table source.

The 781 numbers are the position-key table of the binary book interchange format: a book file is
unreadable unless both sides agree on them, so they are the format, not someone's expression of it.
Only the numbers are taken; nothing in the source is translated.

Usage: scripts/extract-key-table.py /path/to/reference/src/polyglot/random.cpp
"""

import re
import sys
import urllib.request
from pathlib import Path

COUNT = 781
OUT = Path(__file__).resolve().parent.parent / "chess-core" / "src" / "key_table.rs"

HEADER = '''//! The 781 position-key constants of the binary book interchange format.
//!
//! Generated by `scripts/extract-key-table.py`; see `docs/position-key-format.md` for what each
//! range means and `NOTICE.md` for where the numbers come from. They are the format: a book file
//! is readable only by someone who agrees on them.

pub const KEY_TABLE: [u64; 781] = [
'''


def numbers(source: str) -> list[str]:
    found = re.findall(r"0[xX][0-9a-fA-F]{16}", source)
    if len(found) != COUNT:
        sys.exit(f"{len(found)} constants found, expected {COUNT}: {source[:60]} is not the key table")
    return found


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    where = sys.argv[1]
    if where.startswith("http"):
        body = urllib.request.urlopen(where, timeout=30).read().decode()
    else:
        body = Path(where).read_text()
    values = numbers(body)
    lines = [HEADER]
    for start in range(0, COUNT, 4):
        lines.append("    " + " ".join(f"0x{v[2:].lower()}u64," for v in values[start : start + 4]) + "\n")
    lines.append("];\n")
    OUT.write_text("".join(lines))
    print(f"wrote {COUNT} constants to {OUT}")


if __name__ == "__main__":
    main()
